    /**
     * Add or replace a file in a draft area (settings form / task assistant).
     *
     * @param int $draftitemid
     * @param string $name
     * @param string $content
     * @return array files info of the whole area
     */
    public static function draft_put(int $draftitemid, string $name, string $content): array {
        global $USER;
        $name = self::clean_filename($name);
        if (strlen($content) > self::MAX_FILE) {
            throw new moodle_exception('filetoolarge', 'mpl', '', display_size(self::MAX_FILE));
        }
        $usercontext = \context_user::instance($USER->id);
        $fs = get_file_storage();
        $existing = self::draft_files($draftitemid);
        $total = strlen($content);
        $count = 1;
        foreach ($existing as $f) {
            if ($f->get_filepath() === '/' && $f->get_filename() === $name) {
                continue;
            }
            $total += $f->get_filesize();
            $count++;
        }
        if ($total > self::MAX_FILES_TOTAL) {
            throw new moodle_exception('filestoolarge', 'mpl', '', display_size(self::MAX_FILES_TOTAL));
        }
        if ($count > self::MAX_FILE_COUNT) {
            throw new moodle_exception('toomanyfiles', 'mpl', '', self::MAX_FILE_COUNT);
        }
        if ($old = $fs->get_file($usercontext->id, 'user', 'draft', $draftitemid, '/', $name)) {
            $old->delete();
        }
        $fs->create_file_from_string(['contextid' => $usercontext->id, 'component' => 'user', 'filearea' => 'draft',
            'itemid' => $draftitemid, 'filepath' => '/', 'filename' => $name, 'userid' => $USER->id], $content);
        return self::files_info(self::draft_files($draftitemid), false);
    }

