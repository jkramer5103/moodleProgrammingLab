    /**
     * Number of graded attempts of a user.
     *
     * @param int $userid
     * @return int
     */
    public function attempts_used(int $userid): int {
        global $DB;
        return $DB->count_records('mpl_submissions', ['mplid' => $this->mpl->id, 'userid' => $userid]);
    }

    /**
     * Settings that apply to a user: the activity settings, changed by group and user overrides.
     *
     * Several group overrides: the most generous value counts. A user override wins over group overrides.
     *
     * @param int $userid
     * @return stdClass duedate, cutoffdate, maxattempts, override (bool)
     */
    public function effective(int $userid): stdClass {
        global $DB;
        if (isset($this->effectivecache[$userid])) {
            return $this->effectivecache[$userid];
        }
        $out = (object)['duedate' => (int)$this->mpl->duedate, 'cutoffdate' => (int)$this->mpl->cutoffdate,
            'maxattempts' => (int)$this->mpl->maxattempts, 'override' => false];
        $overrides = $userid ? $DB->get_records('mpl_overrides', ['mplid' => $this->mpl->id]) : [];
        if ($overrides) {
            $groupids = array_keys(groups_get_all_groups($this->course->id, $userid, 0, 'g.id'));
            $group = null;
            $user = null;
            foreach ($overrides as $o) {
                if ($o->userid && (int)$o->userid === $userid) {
                    $user = $o;
                } else if ($o->groupid && in_array((int)$o->groupid, $groupids)) {
                    $group = $group ? self::lenient($group, $o) : clone $o;
                }
            }
            foreach ([$group, $user] as $o) {
                if (!$o) {
                    continue;
                }
                foreach (['duedate', 'cutoffdate', 'maxattempts'] as $field) {
                    if ($o->$field !== null) {
                        $out->$field = (int)$o->$field;
                        $out->override = true;
                    }
                }
            }
        }
        return $this->effectivecache[$userid] = $out;
    }

    /**
     * The more generous of two overrides (later dates, more attempts; 0 = no limit).
     *
     * @param stdClass $a
     * @param stdClass $b
     * @return stdClass
     */
    protected static function lenient(stdClass $a, stdClass $b): stdClass {
        $out = clone $a;
        foreach (['duedate', 'cutoffdate', 'maxattempts'] as $field) {
            if ($b->$field === null) {
                continue;
            }
            if ($out->$field === null) {
                $out->$field = $b->$field;
            } else if ((int)$out->$field === 0 || (int)$b->$field === 0) {
                $out->$field = 0;
            } else {
                $out->$field = max((int)$out->$field, (int)$b->$field);
            }
        }
        return $out;
    }

    /**
     * Remaining attempts (null = unlimited).
     *
     * @param int $userid
     * @return int|null
     */
    public function attempts_left(int $userid): ?int {
        $max = $this->effective($userid)->maxattempts;
        if (empty($max)) {
            return null;
        }
        return max(0, $max - $this->attempts_used($userid));
    }

    /**
     * Is handing in still possible for the user (cut-off date, incl. overrides)?
     *
     * @param int $userid
     * @return bool
     */
    public function is_open(int $userid): bool {
        $cutoff = $this->effective($userid)->cutoffdate;
        return empty($cutoff) || time() <= $cutoff;
    }

    /**
     * Why the user cannot submit right now, or null.
     *
     * @param int $userid
     * @return string|null
     */
    public function submit_blocker(int $userid): ?string {
        if (!$this->can_submit()) {
            return get_string('nosubmitcapability', 'mpl');
        }
        if (!$this->is_open($userid)) {
            return get_string('submissionsclosed', 'mpl');
        }
        $left = $this->attempts_left($userid);
        if ($left !== null && $left <= 0) {
            return get_string('noattemptsleft', 'mpl');
        }
        return null;
    }

