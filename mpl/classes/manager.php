     * @return bool
     */
    public function seb_keys_valid(string $url, ?string $confighash, ?string $bekhash, bool $useragent): bool {
        $url = preg_replace('/#.*$/', '', $url);
        $confighash = $confighash !== null ? strtolower(trim($confighash)) : null;
        $bekhash = $bekhash !== null ? strtolower(trim($bekhash)) : null;
        $matches = function(?string $hash, array $keys) use ($url) {
            if (!$hash) {
                return false;
            }
            foreach ($keys as $key) {
                if (hash_equals(hash('sha256', $url . $key), $hash)) {
                    return true;
                }
            }
            return false;
        };
        switch ((int)$this->mpl->sebmode) {
            case self::SEB_CONFIG:
                return $matches($confighash, [seb::config_key($this->seb_settings())]);
            case self::SEB_KEYS:
                $keys = $this->seb_allowed_keys();
                return $matches($confighash, $keys) || $matches($bekhash, $keys);
            case self::SEB_ANY:
                return $useragent || !empty($confighash) || !empty($bekhash);
        }
        return true;
    }

    /**
     * Check the current request (page load) for SEB and store the result in the session.
     *
     * @return bool
     */
    public function seb_check_request(): bool {
        global $FULLME;
        if (!$this->seb_required()) {
            return true;
        }
        $ok = $this->seb_keys_valid((string)$FULLME, $_SERVER['HTTP_X_SAFEEXAMBROWSER_CONFIGKEYHASH'] ?? null,
            $_SERVER['HTTP_X_SAFEEXAMBROWSER_REQUESTHASH'] ?? null, seb::is_seb_useragent());
        if ($ok) {
            $this->set_seb_session(true);
        }
        return $ok || $this->seb_session_ok();
    }

    /**
     * SEB settings of the configuration generated by Moodle.
     *
     * @return array
     */
    public function seb_settings(): array {
        return seb::settings(new \moodle_url('/mod/mpl/view.php', ['id' => $this->cm->id]),
            new \moodle_url('/mod/mpl/view.php', ['id' => $this->cm->id, 'sebquit' => 1]),
            (string)$this->mpl->sebquitpassword);
    }

    /**
     * Log an exam event.
     *
     * @param int $userid
     * @param string $event start, left, paste, sebfail
     * @param string $detail
     * @param int $duration seconds
     */
    public function log_exam_event(int $userid, string $event, string $detail = '', int $duration = 0): void {
        global $DB;
        if (empty($this->mpl->exammode) || !in_array($event, ['start', 'left', 'paste', 'sebfail'])) {
            return;
        }
        if ($DB->count_records('mpl_examlog', ['mplid' => $this->mpl->id, 'userid' => $userid]) >= 1000) {
            return;
        }
        $DB->insert_record('mpl_examlog', (object)['mplid' => $this->mpl->id, 'userid' => $userid, 'event' => $event,
            'detail' => \core_text::substr(clean_param($detail, PARAM_TEXT), 0, 250),
            'duration' => max(0, min($duration, 86400)), 'timecreated' => time()]);
    }

    /**
     * Exam events per user: count and seconds outside of the window.
     *
     * @return array userid => {lefts, seconds, pastes, sebfails, last}
     */
    public function exam_summary(): array {
        global $DB;
        $rows = $DB->get_records_sql("SELECT userid,
                                             SUM(CASE WHEN event = 'left' THEN 1 ELSE 0 END) AS lefts,
                                             SUM(CASE WHEN event = 'left' THEN duration ELSE 0 END) AS seconds,
                                             SUM(CASE WHEN event = 'paste' THEN 1 ELSE 0 END) AS pastes,
                                             SUM(CASE WHEN event = 'sebfail' THEN 1 ELSE 0 END) AS sebfails,
                                             MAX(timecreated) AS last
                                        FROM {mpl_examlog}
                                       WHERE mplid = ?
                                    GROUP BY userid", [$this->mpl->id]);
        return $rows;
    }
