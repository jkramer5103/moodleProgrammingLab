    /**
     * Grade all submissions again with the current tests.
     *
     * The random inputs of each attempt are reproduced (same seed), so a changed grade comes from the
     * changed tests and not from new random values.
     *
     * @param bool $apply false = only compute what would change
     * @param callable|null $progress called with (done, total)
     * @return array summary: total, changed, errors, rows [{submissionid, userid, attempt, old, new}]
     */
    public function regrade(bool $apply, ?callable $progress = null): array {
        global $DB, $CFG;
        require_once($CFG->dirroot . '/mod/mpl/lib.php');
        $subs = $DB->get_recordset('mpl_submissions', ['mplid' => $this->mpl->id], 'userid, attempt',
            'id, userid, attempt, code, fraction, result');
        $total = $DB->count_records('mpl_submissions', ['mplid' => $this->mpl->id]);
        $tests = $this->get_tests();
        $hash = $this->tests_hash();
        $runner = new runner();
        $summary = ['total' => $total, 'changed' => 0, 'errors' => 0, 'rows' => []];
        $done = 0;
        foreach ($subs as $sub) {
            $old = json_decode((string)$sub->result, true) ?: [];
            try {
                $result = $runner->evaluate((string)$sub->code, (string)$this->mpl->reference, $tests, $this->limits(),
                    $this->data_files(), $old['seed'] ?? null);
            } catch (\moodle_exception $e) {
                $summary['errors']++;
                $done++;
                if ($progress) {
                    $progress($done, $total);
                }
                continue;
            }
            $max = (float)($result['max_score'] ?? 0);
            $score = (float)($result['score'] ?? 0);
            $fraction = $max > 0 ? min(1, max(0, $score / $max)) : 0;
            if (abs($fraction - (float)$sub->fraction) > 0.00001) {
                $summary['changed']++;
                $summary['rows'][] = ['submissionid' => (int)$sub->id, 'userid' => (int)$sub->userid,
                    'attempt' => (int)$sub->attempt, 'old' => (float)$sub->fraction, 'new' => $fraction];
            }
            if ($apply) {
                $DB->update_record('mpl_submissions', (object)['id' => $sub->id, 'score' => $score, 'maxscore' => $max,
                    'fraction' => $fraction, 'testshash' => $hash, 'timeregraded' => time(),
                    'result' => json_encode($result, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE)]);
            }
            $done++;
            if ($progress) {
                $progress($done, $total);
            }
        }
        $subs->close();
        if ($apply) {
            mpl_update_grades($this->mpl);
            \cache::make('mod_mpl', 'lastresult')->purge();
        }
        return $summary;
    }

