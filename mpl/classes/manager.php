    /**
     * Beginning of a text file, or null for binary files.
     *
     * @param string $content
     * @param int $lines
     * @param int $chars
     * @return string|null
     */
    public static function text_preview(string $content, int $lines = 40, int $chars = 4000): ?string {
        $head = substr($content, 0, 16384);
        if (strpos($head, "\0") !== false) {
            return null;
        }
        if (!mb_check_encoding($head, 'UTF-8')) {
            // A cut in the middle of a multi-byte character is fine, anything else is binary (or Latin-1).
            $head = mb_strcut($head, 0, strlen($head) - 3, 'UTF-8');
            if (!mb_check_encoding($head, 'UTF-8')) {
                return null;
            }
        }
        $text = str_replace("\r\n", "\n", $head);
        $parts = explode("\n", $text);
        $text = implode("\n", array_slice($parts, 0, $lines));
        if (\core_text::strlen($text) > $chars) {
            $text = \core_text::substr($text, 0, $chars);
        }
        if (count($parts) > $lines || strlen($content) > strlen($head)) {
            $text .= "\n…";
        }
        return $text;
    }

