    /**
     * Create, change or (empty comment) delete a comment.
     *
     * @param int $submissionid
     * @param int $feedbackid 0 = new
     * @param int $line 0 = general comment
     * @param string $comment
     * @return array all feedback of the submission
     */
    public function save_feedback(int $submissionid, int $feedbackid, int $line, string $comment): array {
        global $DB, $USER;
        $sub = $DB->get_record('mpl_submissions', ['id' => $submissionid, 'mplid' => $this->mpl->id], 'id, userid, code, attempt',
            MUST_EXIST);
        $comment = trim(\core_text::substr(str_replace("\r\n", "\n", $comment), 0, 10000));
        $lines = substr_count((string)$sub->code, "\n") + 1;
        $line = max(0, min($line, $lines));
        $now = time();
        if ($feedbackid) {
            $record = $DB->get_record('mpl_feedback', ['id' => $feedbackid, 'submissionid' => $sub->id], '*', MUST_EXIST);
            if ($comment === '') {
                $DB->delete_records('mpl_feedback', ['id' => $record->id]);
            } else {
                $DB->update_record('mpl_feedback', (object)['id' => $record->id, 'comment' => $comment,
                    'authorid' => $USER->id, 'timemodified' => $now]);
            }
        } else if ($comment !== '') {
            $DB->insert_record('mpl_feedback', (object)['mplid' => $this->mpl->id, 'submissionid' => $sub->id,
                'userid' => $sub->userid, 'line' => $line, 'comment' => $comment, 'authorid' => $USER->id,
                'timecreated' => $now, 'timemodified' => $now]);
            $this->notify_feedback($sub);
        }
        return $this->get_feedback($sub->id);
    }

    /**
     * Tell the student about new feedback (at most once per attempt and hour).
     *
     * @param stdClass $sub
     */
    protected function notify_feedback(stdClass $sub): void {
        global $USER;
        $cache = \cache::make('mod_mpl', 'feedbacknotified');
        if ($cache->get($sub->id)) {
            return;
        }
        $cache->set($sub->id, time());
        $url = new \moodle_url('/mod/mpl/submission.php', ['id' => $sub->id]);
        $a = (object)['name' => format_string($this->mpl->name), 'attempt' => $sub->attempt, 'url' => $url->out(false)];
        $message = new \core\message\message();
        $message->component = 'mod_mpl';
        $message->name = 'feedback';
        $message->userfrom = $USER;
        $message->userto = $sub->userid;
        $message->subject = get_string('feedbacknotifysubject', 'mpl', $a);
        $message->fullmessage = get_string('feedbacknotifytext', 'mpl', $a);
        $message->fullmessageformat = FORMAT_PLAIN;
        $message->fullmessagehtml = '';
        $message->smallmessage = get_string('feedbacknotifysubject', 'mpl', $a);
        $message->notification = 1;
        $message->contexturl = $url->out(false);
        $message->contexturlname = format_string($this->mpl->name);
        $message->courseid = $this->course->id;
        try {
            message_send($message);
        } catch (\Throwable $e) {
            debugging('mod_mpl: feedback notification failed: ' . $e->getMessage(), DEBUG_DEVELOPER);
        }
    }

